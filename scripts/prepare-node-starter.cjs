// 正規のnpmで依存なしlockを生成し、browser/main共通の静的テンプレートを作る。
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),{spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..'),source=path.join(root,'tools/release/node-starter');
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'dbt-node-lock-'));
try {
 fs.copyFileSync(path.join(source,'package.json'),path.join(temporary,'package.json'));
 const npm=process.env.npm_execpath || path.join(path.dirname(process.execPath),'node_modules/npm/bin/npm-cli.js');
 const result=spawnSync(process.execPath,[npm,'install','--package-lock-only','--ignore-scripts','--offline','--no-audit','--no-fund'],{cwd:temporary,encoding:'utf8'});
 if(result.status!==0)throw new Error(result.stderr||result.error?.message||'npm lock generation failed');
 fs.copyFileSync(path.join(temporary,'package-lock.json'),path.join(source,'package-lock.json'));
 const data=Object.fromEntries(['package.json','package-lock.json','server.cjs'].map(file=>[file,fs.readFileSync(path.join(source,file),'utf8')]));
 fs.writeFileSync(path.join(root,'app/src/node-starter-data.js'),'// Generated by scripts/prepare-node-starter.cjs using npm. Do not hand-edit the lock.\n(function(root){const data='+JSON.stringify(data,null,2)+';if(typeof module==="object"&&module.exports)module.exports=data;else root.NodeStarterData=data;})(typeof window==="object"?window:globalThis);\n');
 console.log('Generated canonical npm lock and offline Node starter template');
} finally {
 if(path.dirname(temporary)!==os.tmpdir()||!path.basename(temporary).startsWith('dbt-node-lock-'))throw new Error('Unsafe temporary path');
 fs.rmSync(temporary,{recursive:true,force:true});
}
